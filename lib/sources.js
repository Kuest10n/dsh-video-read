/**
 * Reject URLs that could reach the local machine or a private network before
 * they are handed to yt-dlp.
 * @param {string} url
 * @returns {URL}
 */
export function assertPublicHttpUrl(url) {
  let parsed
  try {
    parsed = new URL(url)
  } catch {
    throw new Error(`invalid URL: ${url}`)
  }
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
    throw new Error('only http(s) links are supported')
  }
  const host = parsed.hostname.toLowerCase().replace(/^\[|\]$/g, '')
  if (isPrivateAddress(host)) throw new Error(privateAddressError(host))
  return parsed
}

/** True for loopback/private/link-local/reserved hostnames and IP literals. */
export function isPrivateAddress(host) {
  // URL.hostname keeps IPv6 brackets; strip them plus any zone id.
  const value = String(host).toLowerCase().replace(/^\[|\]$/g, '').replace(/%.*$/, '')
  if (!value) return true
  if (value === 'localhost' || value.endsWith('.localhost') || value.endsWith('.local')) return true
  if (isIP(value) === 4) return isPrivateIpv4(value)
  if (isIP(value) === 6) {
    const mapped = ipv6MappedIpv4(value)
    if (mapped) return isPrivateIpv4(mapped)
    return isPrivateIpv6(value)
  }
  // Bare IPv6-looking strings that the URL parser could hand us.
  if (value.includes(':')) {
    const mapped = ipv6MappedIpv4(value)
    if (mapped) return isPrivateIpv4(mapped)
    return isPrivateIpv6(value)
  }
  return false
}

function isPrivateIpv4(value) {
  const [a, b, c] = value.split('.').map(Number)
  return (
    a === 0 || // 0.0.0.0/8
    a === 10 || // 10/8
    a === 127 || // loopback
    (a === 100 && b >= 64 && b <= 127) || // 100.64/10 CGNAT
    (a === 169 && b === 254) || // link-local
    (a === 172 && b >= 16 && b <= 31) || // 172.16/12
    (a === 192 && b === 0 && c === 0) || // 192.0.0.0/24 IETF
    (a === 192 && b === 0 && c === 2) || // 192.0.2.0/24 TEST-NET-1
    (a === 192 && b === 168) || // 192.168/16
    (a === 198 && (b === 18 || b === 19)) || // 198.18/15 benchmark
    (a === 198 && b === 51 && c === 100) || // 198.51.100.0/24 TEST-NET-2
    (a === 203 && b === 0 && c === 113) || // 203.0.113.0/24 TEST-NET-3
    (a >= 224 && a <= 239) || // multicast
    a >= 240 // reserved / broadcast
  )
}

function isPrivateIpv6(value) {
  const groups = expandIpv6(value)
  if (!groups) return /^(?:f[cd]|fe[89ab])[0-9a-f]{2}:/i.test(value)
  const [g0] = groups
  if (groups.every((group) => group === 0)) return true // ::
  if (groups.slice(0, 7).every((group) => group === 0) && groups[7] === 1) return true // ::1
  if ((g0 & 0xfe00) === 0xfc00) return true // fc00::/7 unique-local
  if ((g0 & 0xffc0) === 0xfe80) return true // fe80::/10 link-local
  return false
}

/** Expand an IPv6 literal into 8 numeric hextets (null when unparseable). */
function expandIpv6(value) {
  const text = value.includes('%') ? value.slice(0, value.indexOf('%')) : value
  if (text.includes('.')) return null // mixed forms handled by ipv6MappedIpv4
  const halves = text.split('::')
  if (halves.length > 2) return null
  const left = halves[0] ? halves[0].split(':') : []
  const right = halves.length === 2 && halves[1] ? halves[1].split(':') : []
  const fill = 8 - left.length - right.length
  if (halves.length === 1) {
    if (left.length !== 8) return null
    return left.map((part) => parseInt(part, 16))
  }
  if (fill < 0) return null
  const groups = [...left, ...Array(fill).fill('0'), ...right].map((part) => parseInt(part, 16))
  return groups.some((group) => !Number.isFinite(group)) ? null : groups
}

/** Return the embedded IPv4 address for ::ffff:a.b.c.d / ::ffff:7f00:1 styles. */
function ipv6MappedIpv4(value) {
  if (value.includes('.')) {
    const tail = value.slice(value.lastIndexOf(':') + 1)
    return /^\d{1,3}(?:\.\d{1,3}){3}$/.test(tail) ? tail : null
  }
  const groups = expandIpv6(value)
  if (!groups) return null
  const [g5, g6, g7] = [groups[5], groups[6], groups[7]]
  if (groups.slice(0, 5).some((group) => group !== 0)) return null
  if (g5 !== 0 && g5 !== 0xffff) return null
  return [g6 >> 8, g6 & 0xff, g7 >> 8, g7 & 0xff].join('.')
}

function privateAddressError(host) {
  return /^\d|:/.test(host)
    ? `refusing to fetch a private address: ${host}`
    : `refusing to fetch a local host: ${host}`
}

/**
 * Like assertPublicHttpUrl, but also resolves the hostname and rejects names
 * that resolve to loopback/private/link-local addresses (DNS-based SSRF).
 * @param {string} url
 * @returns {Promise<URL>}
 */
export async function assertPublicUrlResolvesPublicly(url) {
  const parsed = assertPublicHttpUrl(url)
  const host = parsed.hostname.toLowerCase().replace(/^\[|\]$/g, '')
  if (isIP(host)) return parsed
  let addresses
  try {
    addresses = await lookup(host, { all: true, verbatim: true })
  } catch (error) {
    throw new Error(`could not resolve ${host}: ${error.message}`)
  }
  if (!addresses.length) throw new Error(`no address found for ${host}`)
  for (const entry of addresses) {
    if (isPrivateAddress(entry.address)) {
      throw new Error(`refusing to fetch ${host}: it resolves to a private address (${entry.address})`)
    }
  }
  return parsed
}

/**
 * Resolve any supported source into a normalized descriptor.
 * @param {object} options
 * @param {string} options.source user input
 * @param {boolean} options.download whether the media file must be present
 * @returns {Promise<object>} descriptor with metadata, cues, filePath and artifactsDir
 */
const DRM_HOSTS = [
  'netflix.com',
  'disneyplus.com',
  'hulu.com',
  'iqiyi.com',
  'v.qq.com',
  'youku.com',
  'wetv.vip',
  'primevideo.com',
  'hbomax.com',
  'max.com',
]
const DRM_MESSAGE =
  'this platform is DRM-protected; dsh-video-read does not bypass DRM and cannot read it. ' +
  'Use your own downloaded copy (local file) for content you are allowed to watch, or read a non-DRM source.'

function assertNotDrm(url) {
  let host = ''
  try {
    host = new URL(url).hostname.toLowerCase().replace(/^www\./, '')
  } catch {
    return
  }
  if (DRM_HOSTS.some((entry) => host === entry || host.endsWith(`.${entry}`))) {
    throw new Error(`unsupported source: ${host} — ${DRM_MESSAGE}`)
  }
}

const DIRECT_MEDIA_EXTENSIONS = new Set(['.mp4', '.webm', '.mkv', '.mov', '.m4v', '.flv', '.avi', '.ts'])
const BROWSER_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

/**
 * Return the lowercase video extension when the URL path looks like a direct
 * media file (`https://host/path/clip.mp4?token=...`), else null.
 * @param {string} url
 * @returns {string | null}
 */
export function directMediaExtension(url) {
  try {
    const ext = extname(new URL(url).pathname).toLowerCase()
    return DIRECT_MEDIA_EXTENSIONS.has(ext) ? ext : null
  } catch {
    return null
  }
}

/** Reject downloads whose first bytes are obviously text (HTML/JSON error pages). */
async function assertLooksLikeMedia(filePath) {
  const handle = await open(filePath, 'r')
  try {
    const buffer = Buffer.alloc(4096)
    const { bytesRead } = await handle.read(buffer, 0, buffer.length, 0)
    const head = buffer.subarray(0, bytesRead).toString('utf8').replace(/^\uFEFF/, '').trimStart()
    if (/^[<{[]/.test(head)) {
      throw new Error(
        'the URL returned text (HTML/JSON) instead of video data; pass a direct media link or a page URL yt-dlp supports',
      )
    }
  } finally {
    await handle.close().catch(() => {})
  }
}

/**
 * Download a direct media URL without yt-dlp.
 *
 * Uses fetch defaults first because some static hosts (media.w3.org) answer 403
 * when a non-browser UA/referer combination is sent; a browser-UA retry covers
 * CDNs that require it. Every redirect hop is re-validated against the public
 * URL guard so a public link cannot be bounced into the local network (SSRF).
 */
async function resolveDirectMedia(source, options) {
  const { cfg = {}, artifactsBase, ff, signal, download = true, log = () => {} } = options
  await assertPublicUrlResolvesPublicly(source)
  const parsed = new URL(source)
  const ext = directMediaExtension(source) ?? '.mp4'
  const title = decodeURIComponent(parsed.pathname.split('/').filter(Boolean).pop() ?? 'video') || 'video'
  const dir = artifactsDir(artifactsBase, title, `url-${shortHash(source)}`)
  await mkdir(dir, { recursive: true })
  const filePath = join(dir, `source${ext}`)
  const maxBytes = Number(cfg.maxMediaBytes) > 0 ? cfg.maxMediaBytes : 1_200_000_000
  // A cached direct download is only reused when it is still the same URL and
  // still the byte count recorded for it; a truncated file left by a crash must
  // not be mistaken for complete media.
  let cachedMeta = null
  try {
    cachedMeta = JSON.parse(await readFile(join(dir, 'source.json'), 'utf8'))
  } catch {}
  let cached = false
  if (existsSync(filePath)) {
    const info = await stat(filePath)
    cached =
      info.size > 0 &&
      cachedMeta?.kind === 'direct' &&
      cachedMeta?.webpageUrl === source &&
      Number(cachedMeta?.bytes) === info.size
  }
  if (download && !cached) {
    log('direct media: downloading the URL')
    try {
      await downloadToFile(source, filePath, {
        signal,
        idleTimeoutMs: 45_000,
        maxBytes,
        validateUrl: assertPublicUrlResolvesPublicly,
      })
    } catch (error) {
      log(`direct media: retrying with a browser user agent (${error.message})`)
      await downloadToFile(source, filePath, {
        signal,
        idleTimeoutMs: 45_000,
        maxBytes,
        validateUrl: assertPublicUrlResolvesPublicly,
        headers: { 'user-agent': BROWSER_UA, accept: '*/*' },
      })
    }
    await assertLooksLikeMedia(filePath)
  }
  let cacheNote = null
  // A cached file is only reused after the same magic-byte sanity check a fresh
  // download gets: a crash-truncated file or a CDN error page saved under the
  // final name must not turn into a permanent “successful” probe.
  if (cached) {
    try {
      await assertLooksLikeMedia(filePath)
    } catch (error) {
      await rm(filePath, { force: true }).catch(() => {})
      cached = false
      cacheNote = `discarded an unusable cached download (${error.message})`
    }
  }
  const hasFile = existsSync(filePath)
  const meta = {
    kind: 'direct',
    input: source,
    webpageUrl: source,
    videoId: null,
    title,
    owner: null,
    durationSec: 0,
    width: null,
    height: null,
    hasAudio: null,
    hasVideo: null,
    sizeBytes: hasFile ? (await stat(filePath)).size : null,
    subtitles: { cues: [], languages: [], note: null },
    notes: [
      'downloaded directly from the URL (no yt-dlp needed)',
      ...(cacheNote ? [cacheNote] : []),
    ],
    filePath: hasFile ? filePath : null,
    cacheDir: dir,
    artifactsDir: dir,
    cached,
  }
  // Probe a cached download even when this call asked for metadata only, so a
  // repeated `video_probe` reports the real duration instead of 00:00.
  if (hasFile && ff?.available) {
    try {
      const probe = await probeMedia(ff, filePath, { signal })
      meta.durationSec = probe.durationSec
      meta.width = probe.width
      meta.height = probe.height
      meta.hasAudio = probe.hasAudio
      meta.hasVideo = probe.hasVideo
    } catch (error) {
      meta.notes.push(`probe of the downloaded media failed: ${error.message}`)
    }
  }
  await persistRecords(meta, dir, meta.subtitles)
  await writeCacheMeta(dir, 'source.json', {
    kind: 'direct',
    bytes: meta.sizeBytes,
    webpageUrl: source,
    resolvedAt: new Date().toISOString(),
  })
  return meta
}

export async function resolveSource(options) {
  const { cfg = {}, cwd, signal, download = true, log = () => {}, ctx } = options
  const source = String(options.source ?? '').trim()
  if (!source) throw new Error('source is required: pass a Bilibili URL or a local video path')
  const artifactsBase = cwd
  await prepareArtifactsBase(artifactsBase, cfg, log)
  const ff = await resolveFfmpeg(cfg, { signal, log })
  let meta
  if (isUrl(source)) {
    assertNotDrm(source)
    const classified = classifyUrl(source)
    if (!classified) throw new Error(`invalid URL: ${source}`)
    if (directMediaExtension(source)) {
      meta = await resolveDirectMedia(source, { cfg, cwd, signal, ff, download, artifactsBase, log })
    } else if (classified.kind === 'bilibili' || classified.kind === 'bilibili-short') {
      meta = await resolveBilibiliSource(source, { cfg, cwd, signal, ff, download, artifactsBase, log })
    } else if (classified.kind === 'youtube') {
      meta = await resolveYoutubeSource(source, { cfg, cwd, signal, ff, download, artifactsBase, log, kind: 'youtube' })
    } else if (classified.kind === 'unknown') {
      // Generic web fallback: yt-dlp supports far more sites than the plugin
      // special-cases. Refuse local/private hosts (including DNS-resolved ones)
      // before handing it a URL.
      await assertPublicUrlResolvesPublicly(source)
      meta = await resolveYoutubeSource(source, { cfg, cwd, signal, ff, download, artifactsBase, log, kind: 'yt-dlp' })
    } else {
      throw new Error(unsupportedMessage(classified.kind))
    }
  } else if (/^(?:(?:www|m|mobile)\.)?bilibili\.com\/|^b23\.tv\//i.test(source)) {
    const normalized = /^b23\.tv\//i.test(source) ? source : `https://${source.replace(/^\/+/, '')}`
    meta = await resolveBilibiliSource(normalized, {
      cfg,
      cwd,
      signal,
      ff,
      download,
      artifactsBase,
      log,
    })
  } else {
    meta = await resolveLocal(source, { ctx, cwd, signal, ff, artifactsBase })
  }
  meta.ffmpeg = ff
  return meta
}

