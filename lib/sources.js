const VIDEO_EXTENSIONS = new Set([
  '.mp4', '.mkv', '.webm', '.mov', '.flv', '.avi', '.m4v', '.ts', '.m2ts', '.wmv', '.mpg', '.mpeg', '.ogv',
])
const SUBTITLE_EXTENSIONS = ['.srt', '.vtt', '.ass']
const ARTIFACT_DIR = '.video-read'
const WINDOWS_RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i

export function isUrl(input) {
  return /^https?:\/\//i.test(String(input).trim())
}

/**
 * Turn a remote title into a single safe Windows/POSIX path segment: strips
 * control/format characters and separators, collapses runs, trims leading and
 * trailing dots/spaces, and rejects reserved device names.
 */
export function sanitizeSlug(value) {
  const slug = String(value ?? '')
    .normalize('NFKC')
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f-\u009f\u200e\u200f\u202a-\u202e\u2066-\u2069]+/g, '')
    .replace(/[\\/:*?"<>|]+/g, '-')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^[.\-\s]+|[.\-\s]+$/g, '')
    .slice(0, 48)
  if (!slug || WINDOWS_RESERVED.test(slug)) return 'video'
  return slug
}

function shortHash(value) {
  return createHash('sha1').update(String(value)).digest('hex').slice(0, 10)
}

async function resolveLocalPath(ctx, source, cwd, signal) {
  // Never swallow DSH fs-policy errors: a restricted/read-only session must not
  // be able to read arbitrary local videos just because the plugin falls back
  // to a raw path join. The fallback exists only for host-less unit tests.
  if (ctx?.fs?.resolve && ctx?.fs?.processPath) {
    const target = await ctx.fs.resolve(source, { cwd, signal })
    const absolute = await ctx.fs.processPath(target, { signal })
    if (!absolute) throw new Error(`could not resolve local path: ${source}`)
    return absolute
  }
  return isAbsolute(source) ? source : resolve(cwd, source)
}

async function findSidecarSubtitle(filePath) {
  const dir = dirname(filePath)
  const base = basename(filePath, extname(filePath))
  let entries
  try {
    entries = await readdir(dir, { withFileTypes: true })
  } catch {
    return null
  }
  const candidates = []
  for (const entry of entries) {
    if (!entry.isFile()) continue
    const name = entry.name
    if (!SUBTITLE_EXTENSIONS.some((ext) => name.toLowerCase().endsWith(ext))) continue
    // Require an exact stem boundary: "talk.zh.srt" belongs to talk.mp4, but
    // "talk2.zh.srt" or "another.srt" must not be picked up by prefix matching.
    if (!name.toLowerCase().startsWith(`${base.toLowerCase()}.`)) continue
    candidates.push(name)
  }
  if (!candidates.length) return null
  const lower = (name) => name.toLowerCase()
  candidates.sort((a, b) => {
    const score = (name) => {
      const value = lower(name)
      if (value.includes('.zh')) return 1
      if (value.endsWith('.srt')) return 2
      if (value.endsWith('.vtt')) return 3
      return 4
    }
    return score(a) - score(b) || a.localeCompare(b)
  })
  const chosen = join(dir, candidates[0])
  try {
    const info = await stat(chosen)
    if (info.size > 5_000_000) return null
    const text = await readFile(chosen, 'utf8')
    const ext = extname(chosen).toLowerCase()
    const cues = ext === '.ass' ? parseAss(text) : parseSrtOrVtt(text)
    return { path: chosen, cues, format: ext.slice(1) }
  } catch {
    return null
  }
}

function artifactsDir(cwd, stem, key) {
  return join(cwd, ARTIFACT_DIR, `${sanitizeSlug(stem)}-${shortHash(key)}`)
}

/**
 * Keep <workspace>/.video-read/ from being committed by accident and prune
 * artifact directories older than cacheTtlDays (best effort; never fatal).
 */
async function prepareArtifactsBase(cwd, cfg = {}, log = () => {}) {
  const base = join(cwd, ARTIFACT_DIR)
  try {
    await mkdir(base, { recursive: true })
    const ignore = join(base, '.gitignore')
    try {
      await stat(ignore)
    } catch {
      await writeFile(ignore, '# generated by dsh-video-read; ignore cached media\n*\n!.gitignore\n', 'utf8')
    }
    if (cfg.pruneArtifacts === false) return
    const ttlDays = Number(cfg.cacheTtlDays)
    const ttlMs = (Number.isFinite(ttlDays) && ttlDays > 0 ? ttlDays : 14) * 86_400_000
    const cutoff = Date.now() - ttlMs
    let removed = 0
    for (const entry of await readdir(base, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      const path = join(base, entry.name)
      try {
        const info = await stat(path)
        if (info.mtimeMs < cutoff) {
          await rm(path, { recursive: true, force: true })
          removed += 1
        }
      } catch {}
    }
    if (removed) log(`pruned ${removed} artifact director${removed === 1 ? 'y' : 'ies'} older than ${ttlMs / 86_400_000} days`)
  } catch {}
}

async function persistJson(file, value) {
  await mkdir(dirname(file), { recursive: true })
  const tmp = `${file}.tmp-${process.pid}-${Date.now().toString(36)}`
  await writeFile(tmp, JSON.stringify(value, null, 2), 'utf8')
  await rename(tmp, file)
}

async function persistRecords(meta, artifacts, timeline) {
  await mkdir(artifacts, { recursive: true })
  const { cues, ...rest } = meta.subtitles ?? {}
  await persistJson(join(artifacts, 'meta.json'), {
    ...meta,
    subtitles: { ...rest, count: Array.isArray(cues) ? cues.length : 0 },
  })
  if (timeline?.cues?.length) await persistJson(join(artifacts, 'timeline.json'), timeline.cues)
}

async function resolveLocal(source, options) {
  const { ctx, cwd, signal, ff, artifactsBase } = options
  const filePath = await resolveLocalPath(ctx, source, cwd, signal)
  let info
  try {
    info = await stat(filePath)
  } catch {
    throw new Error(`local file not found: ${filePath} (pass an absolute path or a path relative to the workspace)`)
  }
  if (!info.isFile()) throw new Error(`not a regular file: ${filePath}`)
  const ext = extname(filePath).toLowerCase()
  if (!VIDEO_EXTENSIONS.has(ext)) {
    throw new Error(`unsupported local file extension "${ext || '(none)'}"; expected one of: ${[...VIDEO_EXTENSIONS].join(', ')}`)
  }
  const key = `${filePath}|${info.size}|${info.mtimeMs}`
  const cacheDir = artifactsDir(artifactsBase, basename(filePath, ext), key)
  await mkdir(cacheDir, { recursive: true })

  const notes = []
  let probe = null
  if (ff?.available) {
    try {
      probe = await probeMedia(ff, filePath, { signal })
    } catch (error) {
      throw new Error(`could not read media metadata: ${error.message} (is the file corrupt or unsupported?)`)
    }
  } else {
    notes.push(ff?.note ?? 'ffmpeg/ffprobe unavailable; duration and streams could not be probed')
  }
  if (probe && !probe.hasVideo) throw new Error(`local file has no video stream: ${filePath}`)
  const sidecar = await findSidecarSubtitle(filePath)
  if (sidecar) notes.push(`subtitle sidecar: ${basename(sidecar.path)} (${sidecar.format}, ${sidecar.cues.length} cues)`)
  const meta = {
    kind: 'local',
    input: source,
    filePath,
    title: basename(filePath),
    durationSec: probe?.durationSec ?? 0,
    width: probe?.width ?? null,
    height: probe?.height ?? null,
    hasAudio: probe?.hasAudio ?? null,
    hasVideo: probe?.hasVideo ?? null,
    videoCodec: probe?.videoCodec ?? null,
    sizeBytes: info.size,
    resolvedAt: new Date().toISOString(),
    cached: false,
    subtitles: {
      cues: sidecar?.cues ?? [],
      languages: sidecar ? [sidecar.format] : [],
      note: sidecar ? null : 'no sidecar subtitle file found',
    },
    notes,
    artifactsDir: cacheDir,
    cacheDir,
  }
  await persistRecords(meta, cacheDir, meta.subtitles)
  return meta
}

async function resolveBilibiliSource(source, options) {
  const { cfg, cwd, signal, ff, download, artifactsBase, log } = options
  const cookieFile = cfg.cookieFile
  const limits = {
    maxVideoMinutes: Number(cfg.maxVideoMinutes) || 180,
    maxMediaBytes: Number(cfg.maxMediaBytes) || 1_200_000_000,
  }
  // One metadata pass is enough for probe; a download reuses it instead of
  // repeating view/nav/subtitle calls.
  const first = await resolveBilibili(source, {
    cookieFile,
    signal,
    download: false,
    ff,
    log,
    quality: cfg.quality,
    ...limits,
  })
  // The artifact directory is keyed by video *and part*: a multi-part collection
  // must never reuse the cached source.mp4 of another episode.
  const mediaKey = `${first.bvid}|p${first.page ?? 1}|cid${first.cid ?? ''}`
  const dir = artifactsDir(artifactsBase, first.title, mediaKey)
  await mkdir(dir, { recursive: true })
  first.artifactsDir = dir
  first.cacheDir = dir
  let meta = first
  const cached = join(dir, 'source.mp4')
  let cachedAt = null
  try {
    const info = await stat(cached)
    if (info.size > 10_000) {
      let recorded = null
      try {
        recorded = JSON.parse(await readFile(join(dir, 'source.json'), 'utf8'))
      } catch {}
      const identityMatches =
        recorded &&
        recorded.bvid === first.bvid &&
        Number(recorded.cid) === Number(first.cid) &&
        Number(recorded.page ?? 1) === Number(first.page ?? 1)
      if (identityMatches) {
        // Trust the cached media only when its recorded size still matches.
        const expected = Number(recorded.bytes)
        if (!Number.isFinite(expected) || Math.abs(expected - info.size) <= Math.max(4096, expected * 0.01)) {
          cachedAt = info
        }
      }
    }
  } catch {}
  if (download) {
    if (cachedAt) {
      meta = {
        ...first,
        filePath: cached,
        cached: true,
        sizeBytes: cachedAt.size,
        notes: [...first.notes, `reused cached download (${(cachedAt.size / 1024 / 1024).toFixed(1)} MB)`],
      }
    } else {
      log(`downloading ${first.bvid} (${first.title})`)
      meta = await resolveBilibili(source, {
        cookieFile,
        signal,
        download: true,
        ff,
        log,
        quality: cfg.quality,
        cacheDir: dir,
        existing: first,
        wbiMixin: first.wbiMixin ?? null,
        ...limits,
      })
      meta.artifactsDir = dir
      meta.cacheDir = dir
      meta.notes = [...(meta.notes ?? []), 'media cached under the workspace .video-read directory']
    }
  }
  if (meta.filePath && ff?.available) {
    try {
      const probe = await probeMedia(ff, meta.filePath, { signal })
      meta.durationSec = probe.durationSec || meta.durationSec
      meta.width = probe.width
      meta.height = probe.height
      meta.hasAudio = probe.hasAudio
      meta.hasVideo = probe.hasVideo
      meta.videoCodec = probe.videoCodec
      meta.sizeBytes = (await stat(meta.filePath)).size
    } catch (error) {
      meta.notes.push(`probe of downloaded media failed: ${error.message}`)
    }
  }
  if (meta.hasVideo === undefined) meta.hasVideo = null
  meta.resolvedAt = new Date().toISOString()
  if (meta.cached === undefined) meta.cached = false
  if (!meta.width && first.dimension) {
    meta.width = Number(first.dimension.width) || null
    meta.height = Number(first.dimension.height) || null
  }
  meta.artifactsDir = dir
  meta.cacheDir = dir
  await persistRecords(meta, dir, meta.subtitles)
  await writeCacheMeta(dir, 'source.json', {
    bvid: meta.bvid,
    cid: meta.cid,
    page: meta.page ?? 1,
    title: meta.title,
    webpageUrl: meta.webpageUrl,
    bytes: meta.sizeBytes ?? null,
    cached: Boolean(meta.cached),
    resolvedAt: new Date().toISOString(),
  })
  return meta
}

